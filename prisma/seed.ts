async function main() {
  const course = await db.course.upsert({
    where: { slug: "put-treydera" },
    update: {},
    create: {
      slug: "put-treydera",
      title: "Путь трейдера",
      description:
        "Структурированный путь от базовых понятий рынка до практики на виртуальном счёте.",
      level: "BEGINNER",
      order: 0,
      published: true,
    },
  });

  let moduleOrder = 0;
  let previousLessonId: string | null = null;

  for (const moduleSeed of CURRICULUM) {
    const mod = await db.module.upsert({
      where: { id: `${course.id}-${moduleOrder}` },
      update: {},
      create: {
        id: `${course.id}-${moduleOrder}`,
        courseId: course.id,
        title: moduleSeed.title,
        order: moduleOrder,
      },
    });

    let lessonOrder = 0;

    for (const lessonSeed of moduleSeed.lessons) {
      const content = { blocks: lessonSeed.content };

      const lesson: Awaited<ReturnType<typeof db.lesson.upsert>> = await db.lesson.upsert({
        where: { moduleId_slug: { moduleId: mod.id, slug: lessonSeed.slug } },
        update: {
          title: lessonSeed.title,
          summary: lessonSeed.summary,
          content,
          xpReward: lessonSeed.xpReward,
          requiredLessonId: previousLessonId,
          published: true,
        },
        create: {
          moduleId: mod.id,
          slug: lessonSeed.slug,
          title: lessonSeed.title,
          summary: lessonSeed.summary,
          content,
          order: lessonOrder,
          xpReward: lessonSeed.xpReward,
          requiredLessonId: previousLessonId,
          published: true,
        },
      });

      let questionOrder = 0;
      for (const q of lessonSeed.questions) {
        await db.question.upsert({
          where: { id: `${lesson.id}-q${questionOrder}` },
          update: {
            prompt: q.prompt,
            options: q.options,
            correctAnswer: q.correctAnswer,
          },
          create: {
            id: `${lesson.id}-q${questionOrder}`,
            lessonId: lesson.id,
            type: "SINGLE_CHOICE",
            prompt: q.prompt,
            options: q.options,
            correctAnswer: q.correctAnswer,
            order: questionOrder,
            xpReward: 5,
          },
        });
        questionOrder++;
      }

      previousLessonId = lesson.id;
      lessonOrder++;
    }
    moduleOrder++;
  }

  const totalLessons = CURRICULUM.reduce((sum, m) => sum + m.lessons.length, 0);
  console.log(
    `Seeded course "${course.title}" with ${CURRICULUM.length} modules and ${totalLessons} lessons.`
  );
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await db.$disconnect();
  });
